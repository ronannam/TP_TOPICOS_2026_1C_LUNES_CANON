void EscribirTexto(uint16_t x, uint16_t y, const char* texto, uint8_t colorIndice, uint8_t tamano) {
    size_t longitud = strlen(texto);

    for(size_t i = 0; i < longitud; i++) {
        uint8_t caracter_actual = texto[i];

        if (tamano == FUENTE_8X8) {
            for(int fila = 0; fila < 8; fila++) {
                uint8_t byte_fila = TODA_LA_FUENTE_8X8[caracter_actual][fila];
                for(int col = 0; col < 8; col++) {
                    uint8_t bit_activo = (byte_fila >> (7 - col)) & 1;
                    if(bit_activo != 0) {
                        gbt_dibujar_pixel(x + col, y + fila, colorIndice);
                    }
                }
            }
        }
        else if(tamano == FUENTE_8X16) {
            for(int fila = 0; fila < 16; fila++) {
                uint8_t byte_fila = TODA_LA_FUENTE_8X16_DATA[caracter_actual][fila];
                for(int col = 0; col < 8; col++) {
                    uint8_t bit_activo = (byte_fila >> (7 - col)) & 1;
                    if(bit_activo != 0) {
                        gbt_dibujar_pixel(x + col, y + fila, colorIndice);
                    }
                }
            }
        }

        x += 8;
    }
}
